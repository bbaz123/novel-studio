const s = '剑在书包夹层里。';
const tries = [
  ['A 无嵌套组', /([\u4e00-\u9fa5]{1,8}?)在(书包)(夹层)(?:里|中|内)?/g],
  ['B 有层级交替', /([\u4e00-\u9fa5]{1,8}?)(?:还|仍|就)?在(书包|背包|包)(更深|里面一点|内侧|夹层|底层|最底下|最里面)?(?:里|中|内)?/g],
  ['C B的层级加非捕获包裹', /([\u4e00-\u9fa5]{1,8}?)(?:还|仍|就)?在(书包|背包|包)(?:(更深|里面一点|内侧|夹层|底层|最底下|最里面))?(?:里|中|内)?/g],
];
for (const [label, re] of tries) {
  const m = re.exec(s);
  console.log(`${label}: ${m ? `whole=${m[0]} | g1=${m[1]} g2=${m[2]} g3=${m[3]}` : 'no match'}`);
}
